import java.lang.*;
public class Escape
{
public static void main(String[] args)
{
System.out.println("Hello//KGCoding//..."); //use backslash to escape sequence. 
System.out.println("Hello\nKGCoding"); //will print KGCoding on next line.
System.out.println("Hello\tKGCoding"); //will print space between hello and KGCoding.
System.out.println("Hello\bKGCoding"); //will print backspace.
}
}  	